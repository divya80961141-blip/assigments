public class methods {
    

public static void main(String[] args)
  {
    add(30, 20);
    sub(100, 10);
    mult(11, 5 );
    div(11, 2);
    
   }
  public static int add(int a,int b)
  {
    return a+b;
   }
   public static  int sub(int  a, int b){
    return  a-b;
   } 
   public static int  mult (int  a, int  b)
   {
    return a*b;
   }
  public static int div(int a, int b)
  {
    return a/b;
   }
}       
